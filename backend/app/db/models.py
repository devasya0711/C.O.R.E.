"""SQLAlchemy mappings for the PostgreSQL system of record.

Only the JSON type has a SQLite variant, for portable unit tests. UUIDs,
timestamps, and collection defaults are generated by the database, not Python.
"""

from __future__ import annotations

from datetime import datetime
from uuid import UUID

from sqlalchemy import (
    JSON,
    Boolean,
    CheckConstraint,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    MetaData,
    String,
    Text,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.dialects.postgresql import UUID as PGUUID
from sqlalchemy.ext.mutable import MutableDict, MutableList
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship


class Base(DeclarativeBase):
    """Shared metadata with stable names for migrations and constraint errors."""

    metadata = MetaData(
        naming_convention={
            "ix": "ix_%(column_0_label)s",
            "uq": "uq_%(table_name)s_%(column_0_name)s",
            "ck": "ck_%(table_name)s_%(constraint_name)s",
            "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
            "pk": "pk_%(table_name)s",
        }
    )


class User(Base):
    """Workspace owner and encrypted GitHub credential storage."""

    __tablename__ = "users"

    id: Mapped[UUID] = mapped_column(
        PGUUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    clerk_id: Mapped[str] = mapped_column(String(128), unique=True, index=True)
    email: Mapped[str] = mapped_column(String(255), unique=True)
    encrypted_github_pat: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )

    repositories: Mapped[list[Repository]] = relationship(
        back_populates="user", cascade="all, delete-orphan", passive_deletes=True
    )


class Repository(Base):
    """Repository metadata; graph contents live in Neo4j."""

    __tablename__ = "repositories"
    __table_args__ = (
        CheckConstraint(
            "status IN ('PENDING', 'INGESTING', 'READY', 'FAILED')", name="status"
        ),
        CheckConstraint("node_count >= 0", name="node_count"),
        CheckConstraint("edge_count >= 0", name="edge_count"),
    )

    id: Mapped[UUID] = mapped_column(
        PGUUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    user_id: Mapped[UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    name: Mapped[str] = mapped_column(String(255))
    repo_url: Mapped[str] = mapped_column(String(512))
    default_branch: Mapped[str] = mapped_column(String(128), server_default="main")
    last_commit_sha: Mapped[str | None] = mapped_column(String(64))
    status: Mapped[str] = mapped_column(String(32), server_default="PENDING")
    node_count: Mapped[int] = mapped_column(Integer, server_default=text("0"))
    edge_count: Mapped[int] = mapped_column(Integer, server_default=text("0"))
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )

    user: Mapped[User] = relationship(back_populates="repositories")
    seam_clusters: Mapped[list[SeamCluster]] = relationship(
        back_populates="repository", cascade="all, delete-orphan", passive_deletes=True
    )
    migration_jobs: Mapped[list[MigrationJob]] = relationship(
        back_populates="repository", cascade="all, delete-orphan", passive_deletes=True
    )
    ingestion_jobs: Mapped[list[IngestionJob]] = relationship(
        back_populates="repository", cascade="all, delete-orphan", passive_deletes=True
    )


class SeamCluster(Base):
    """Persisted community detection results and extraction candidates."""

    __tablename__ = "seam_clusters"
    __table_args__ = (
        CheckConstraint(
            "cohesion_score >= 0.0 AND cohesion_score <= 1.0", name="cohesion_score"
        ),
    )

    id: Mapped[UUID] = mapped_column(
        PGUUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    repo_id: Mapped[UUID] = mapped_column(
        ForeignKey("repositories.id", ondelete="CASCADE"), index=True
    )
    snapshot_version: Mapped[str | None] = mapped_column(String(128))
    community_id: Mapped[int] = mapped_column(Integer)
    suggested_name: Mapped[str] = mapped_column(String(128))
    cohesion_score: Mapped[float] = mapped_column(Float)
    shared_db_tables: Mapped[list[str]] = mapped_column(
        MutableList.as_mutable(
            JSONB(none_as_null=True).with_variant(JSON(none_as_null=True), "sqlite")
        ),
        server_default=text("'[]'"),
    )
    node_ids: Mapped[list[str]] = mapped_column(
        MutableList.as_mutable(
            JSONB(none_as_null=True).with_variant(JSON(none_as_null=True), "sqlite")
        ),
        server_default=text("'[]'"),
    )

    repository: Mapped[Repository] = relationship(back_populates="seam_clusters")
    migration_jobs: Mapped[list[MigrationJob]] = relationship(
        back_populates="seam", cascade="all, delete-orphan", passive_deletes=True
    )


class MigrationJob(Base):
    """Durable CRAG/refactoring state, artifacts, and sandbox outcome."""

    __tablename__ = "migration_jobs"
    __table_args__ = (
        CheckConstraint(
            "status IN ('QUEUED', 'CRAG_EVAL', 'CODING', 'TESTING', "
            "'COMPLETED', 'FAILED')",
            name="status",
        ),
        CheckConstraint(
            "crag_status IN ('PENDING', 'SUFFICIENT', 'AUGMENTED')", name="crag_status"
        ),
        CheckConstraint("retry_count >= 0 AND retry_count <= 3", name="retry_count"),
    )

    id: Mapped[UUID] = mapped_column(
        PGUUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    repo_id: Mapped[UUID] = mapped_column(
        ForeignKey("repositories.id", ondelete="CASCADE"), index=True
    )
    seam_id: Mapped[UUID] = mapped_column(
        ForeignKey("seam_clusters.id", ondelete="CASCADE")
    )
    create_github_pr: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default=text("false")
    )
    snapshot_version: Mapped[str | None] = mapped_column(String(128))
    source_commit_sha: Mapped[str | None] = mapped_column(String(64))
    sandbox_passed: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default=text("false")
    )
    status: Mapped[str] = mapped_column(String(32), server_default="QUEUED")
    crag_status: Mapped[str] = mapped_column(String(32), server_default="PENDING")
    retry_count: Mapped[int] = mapped_column(Integer, server_default=text("0"))
    generated_artifacts: Mapped[dict[str, str]] = mapped_column(
        MutableDict.as_mutable(
            JSONB(none_as_null=True).with_variant(JSON(none_as_null=True), "sqlite")
        ),
        server_default=text("'{}'"),
    )
    sandbox_logs: Mapped[str | None] = mapped_column(Text)
    sandbox_isolation: Mapped[str | None] = mapped_column(String(32))
    sandbox_isolation_note: Mapped[str | None] = mapped_column(Text)
    pr_url: Mapped[str | None] = mapped_column(String(512))
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )

    repository: Mapped[Repository] = relationship(back_populates="migration_jobs")
    seam: Mapped[SeamCluster] = relationship(back_populates="migration_jobs")


class IngestionJob(Base):
    """Ingestion lifecycle required by PRD/architecture, absent from DATABASE.md.

    Progress is an integer percentage. Stage names mirror the four PRD ingestion
    steps, with QUEUED/COMPLETED/FAILED terminal or waiting markers. Workers set
    started_at/completed_at explicitly; SQLAlchemy updates updated_at on writes.
    """

    __tablename__ = "ingestion_jobs"
    __table_args__ = (
        CheckConstraint(
            "status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'FAILED')", name="status"
        ),
        CheckConstraint(
            "stage IN ('QUEUED', 'CLONING', 'AST_PARSING', 'VECTOR_EMBEDDING', "
            "'GRAPH_INDEXING', 'COMPLETED', 'FAILED')",
            name="stage",
        ),
        CheckConstraint("progress >= 0 AND progress <= 100", name="progress"),
    )

    id: Mapped[UUID] = mapped_column(
        PGUUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    repo_id: Mapped[UUID] = mapped_column(
        ForeignKey("repositories.id", ondelete="CASCADE"), index=True
    )
    status: Mapped[str] = mapped_column(String(32), server_default="QUEUED")
    stage: Mapped[str] = mapped_column(String(32), server_default="QUEUED")
    progress: Mapped[int] = mapped_column(Integer, server_default=text("0"))
    error: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )
    started_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    completed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    repository: Mapped[Repository] = relationship(back_populates="ingestion_jobs")
